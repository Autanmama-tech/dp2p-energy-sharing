%% add_grid_quality.m
% Adds grid quality monitoring to the Layer 1 / Layer 2 interface.
%
% Changes made:
%   Layer 1 (ss1_power_plant):
%     - Exposes SMPS output voltage as new output port 5 (V_grid_raw)
%     - Adds Grid_Quality_Monitor subsystem: computes V_grid_quality (0-1)
%
%   Layer 2 (ss2_auction_ctrl):
%     - Adds input port 8: V_grid_quality (0=weak, 1=strong)
%     - Updates auction_engine MATLAB Function with 3-state source logic
%
%   Top model (p2p_microgrid):
%     - Wires SS1 port 5 → SS2 port 8
%
% Grid quality thresholds (Nigerian grid context):
%   V_grid ≥ 11.5V → STRONG  (quality = 1.0) — grid reliable
%   V_grid  10.5–11.5V → WEAK (quality = 0–1) — grid degraded
%   V_grid < 10.5V → FAILED  (quality = 0.0) — no usable grid
%
% Run: >> init_microgrid
%      >> add_grid_quality
% -----------------------------------------------------------------------

function add_grid_quality()

fprintf('=== Adding Grid Quality Monitor ===\n\n');

%% ---------------------------------------------------------------
%  STEP 1: Add V_grid_raw outport to Layer 1 (ss1_power_plant)
%% ---------------------------------------------------------------
mdl1 = 'ss1_power_plant';
if ~bdIsLoaded(mdl1); load_system(mdl1); end
open_system(mdl1);

fprintf('[Layer 1] Adding grid quality monitor...\n');

%% Add Grid Quality Monitor subsystem
gqm = [mdl1 '/Grid_Quality_Monitor'];
try; delete_block(gqm); catch; end

add_block('built-in/Subsystem', gqm, ...
    'Position', [820, 310, 960, 410]);

open_system(gqm);

% Clean default ports
try; delete_block([gqm '/In1']);  catch; end
try; delete_block([gqm '/Out1']); catch; end

% Input: raw SMPS voltage
add_block('built-in/Inport', [gqm '/V_smps'], ...
    'Position', [30, 80, 80, 100], 'Port','1');

% Thresholds (Nigerian grid context)
% V_strong = 11.5V (good regulation)
% V_weak   = 10.5V (below this = unusable)
V_STRONG = 11.5;
V_WEAK   = 10.5;

% Linear quality mapping: quality = (V - V_weak)/(V_strong - V_weak)
% Clipped to [0, 1]
% Implemented as: Gain + Bias → Saturation

% Subtract V_weak (bias)
add_block('simulink/Math Operations/Sum', [gqm '/Sub_Vweak'], ...
    'Position', [120, 75, 160, 105], ...
    'Inputs', '+-', 'IconShape','round');

add_block('simulink/Sources/Constant', [gqm '/V_weak_const'], ...
    'Position', [30, 115, 100, 135], ...
    'Value', num2str(V_WEAK));

% Scale to [0,1] range
K_scale = 1 / (V_STRONG - V_WEAK);   % = 1/1.0 = 1.0
add_block('simulink/Math Operations/Gain', [gqm '/Quality_Scale'], ...
    'Position', [190, 75, 260, 105], ...
    'Gain', num2str(K_scale));

% Clamp to [0, 1]
add_block('simulink/Discontinuities/Saturation', [gqm '/Quality_Clamp'], ...
    'Position', [290, 75, 360, 105], ...
    'UpperLimit', '1', ...
    'LowerLimit', '0');

% Output
add_block('built-in/Outport', [gqm '/V_grid_quality'], ...
    'Position', [400, 80, 450, 100], 'Port','1');

% Wire inside GQM
add_line(gqm, 'V_smps/1',       'Sub_Vweak/1',      'autorouting','on');
add_line(gqm, 'V_weak_const/1', 'Sub_Vweak/2',      'autorouting','on');
add_line(gqm, 'Sub_Vweak/1',    'Quality_Scale/1',  'autorouting','on');
add_line(gqm, 'Quality_Scale/1','Quality_Clamp/1',  'autorouting','on');
add_line(gqm, 'Quality_Clamp/1','V_grid_quality/1', 'autorouting','on');

fprintf('[OK]  Grid_Quality_Monitor subsystem built\n');

%% Wire SMPS output → Grid_Quality_Monitor
try
    add_line(mdl1, 'SMPS_Grid/1', 'Grid_Quality_Monitor/1', 'autorouting','on');
    fprintf('[OK]  SMPS_Grid/1 → Grid_Quality_Monitor\n');
catch ME
    fprintf('[WARN] %s\n', ME.message);
end

%% Add output port 5: V_grid_quality
try; delete_block([mdl1 '/V_grid_quality']); catch; end
add_block('built-in/Outport', [mdl1 '/V_grid_quality'], ...
    'Position', [1050, 435, 1100, 455], 'Port','5');

try
    add_line(mdl1, 'Grid_Quality_Monitor/1', 'V_grid_quality/1', 'autorouting','on');
    fprintf('[OK]  V_grid_quality → Layer 1 output port 5\n');
catch ME
    fprintf('[WARN] %s\n', ME.message);
end

save_system(mdl1, [mdl1 '.slx']);
fprintf('[OK]  Saved %s.slx\n\n', mdl1);

%% ---------------------------------------------------------------
%  STEP 2: Add V_grid_quality input to Layer 2 (ss2_auction_ctrl)
%% ---------------------------------------------------------------
mdl2 = 'ss2_auction_ctrl';
if ~bdIsLoaded(mdl2); load_system(mdl2); end

fprintf('[Layer 2] Adding V_grid_quality input port...\n');

% Add inport 8: V_grid_quality
try; delete_block([mdl2 '/V_grid_quality']); catch; end
add_block('built-in/Inport', [mdl2 '/V_grid_quality'], ...
    'Position', [30, 375, 90, 395], 'Port','8');

% Add ZOH for the new input
try; delete_block([mdl2 '/ZOH_V_grid_quality']); catch; end
add_block('simulink/Discrete/Zero-Order Hold', [mdl2 '/ZOH_V_grid_quality'], ...
    'Position', [160, 370, 230, 395], ...
    'SampleTime', 'AUC.cycle_s');

add_line(mdl2, 'V_grid_quality/1', 'ZOH_V_grid_quality/1', 'autorouting','on');
add_line(mdl2, 'ZOH_V_grid_quality/1', 'Auction_Engine/8',  'autorouting','on');

fprintf('[OK]  V_grid_quality → ZOH → Auction_Engine port 8\n');

%% Update auction function code with 3-state source logic
fprintf('[Layer 2] Updating auction engine with grid quality logic...\n');
update_auction_code(mdl2);

save_system(mdl2, [mdl2 '.slx']);
fprintf('[OK]  Saved %s.slx\n\n', mdl2);

%% ---------------------------------------------------------------
%  STEP 3: Connect SS1 port 5 → SS2 port 8 in top model
%% ---------------------------------------------------------------
top = 'p2p_microgrid';
if ~bdIsLoaded(top); load_system(top); end

fprintf('[Top model] Wiring SS1/5 → SS2/8 (grid quality)...\n');

try
    add_line(top, 'SS1_PowerPlant/5', 'SS2_AuctionCtrl/8', 'autorouting','on');
    fprintf('[OK]  SS1_PowerPlant/5 → SS2_AuctionCtrl/8\n');
catch ME
    fprintf('[WARN] %s\n', ME.message);
end

save_system(top, [top '.slx'], 'SaveDirtyReferencedModels','on');
fprintf('[OK]  Saved %s.slx\n\n', top);

%% ---------------------------------------------------------------
%  SUMMARY
%% ---------------------------------------------------------------
fprintf('=== Grid Quality Monitor — Summary ===\n\n');
fprintf('  Nigerian grid quality is mapped to a 0–1 signal:\n\n');
fprintf('  V_smps ≥ 11.5V → quality = 1.0  (STRONG — grid reliable)\n');
fprintf('  V_smps = 11.0V → quality = 0.5  (WEAK   — degraded supply)\n');
fprintf('  V_smps ≤ 10.5V → quality = 0.0  (FAILED — unusable)\n\n');
fprintf('  Updated source selection logic (3 states):\n\n');
fprintf('  State 1: quality ≥ 0.8 AND V_bat < 11.8V → GRID (protect battery)\n');
fprintf('  State 2: quality < 0.5 AND V_bat ≥ 11.8V → SOLAR (grid too weak)\n');
fprintf('  State 3: quality ≥ 0.5 AND V_bat ≥ 11.8V → SOLAR (save grid)\n');
fprintf('  State 4: V_bat < 11.8V AND quality < 0.8  → GRID (best available)\n\n');
fprintf('  This models real Nigerian grid conditions where:\n');
fprintf('  - Voltage sags during peak demand hours\n');
fprintf('  - Low current delivery cannot power 144W dryer elements\n');
fprintf('  - Solar is preferred when grid is unreliable\n\n');
fprintf('  Ready: run sim(''p2p_microgrid'') to test.\n\n');
end

%% =====================================================================
function update_auction_code(mdl2)
%% Injects updated auction function with 3-state grid quality logic

code = [...
'function [relay_K1, relay_n1, relay_n2, jfi, source_mode, bid_n1, bid_n2, winner] = ...' newline ...
'    auction_engine(bat_voltage, rh_n1, rh_n2, btn_n1, btn_n2, E1_cum, E2_cum, V_grid_quality)' newline ...
'%#codegen' newline ...
'% AutaNet P2P Auction Protocol — Layer 2, 10-second cycle' newline ...
'% Decision 1: Source selection (3-state, Nigerian grid quality aware)' newline ...
'% Decision 2: Dryer priority (bid-based auction on humidity)' newline ...
'' newline ...
'%% Constants' newline ...
'V_GRID_SWITCH  = 11.8;   % V  battery threshold' newline ...
'Q_STRONG       = 0.8;    % grid quality threshold for strong grid' newline ...
'Q_WEAK         = 0.5;    % grid quality threshold for weak grid' newline ...
'RH_CRIT        = 0.80;   % humidity threshold for critical bid' newline ...
'BID_H          = 140;    % units/kWh — critical bid' newline ...
'BID_L          = 100;    % units/kWh — standard bid' newline ...
'' newline ...
'%% Decision 1: Source selection' newline ...
'% Nigerian grid quality aware — 3 states:' newline ...
'%   STRONG grid (q >= 0.8) + battery low  -> use grid, protect battery' newline ...
'%   WEAK grid   (q <  0.5) + solar OK     -> use solar, grid unreliable' newline ...
'%   STRONG grid (q >= 0.5) + solar OK     -> use solar, save grid energy' newline ...
'%   No solar + any grid                   -> use grid regardless' newline ...
'' newline ...
'bat_ok   = (bat_voltage >= V_GRID_SWITCH);' newline ...
'grid_strong = (V_grid_quality >= Q_STRONG);' newline ...
'grid_usable = (V_grid_quality >= Q_WEAK);' newline ...
'' newline ...
'if bat_ok && ~grid_strong' newline ...
'    % Solar OK, grid weak or absent -> prefer solar' newline ...
'    use_solar = true;' newline ...
'elseif bat_ok && grid_strong' newline ...
'    % Both available -> prefer solar to conserve grid' newline ...
'    use_solar = true;' newline ...
'elseif ~bat_ok && grid_usable' newline ...
'    % Battery low, grid usable -> use grid to protect battery' newline ...
'    use_solar = false;' newline ...
'elseif ~bat_ok && ~grid_usable' newline ...
'    % Battery low, grid also weak -> use whatever solar is left' newline ...
'    use_solar = bat_voltage >= 11.6;  % above LVD only' newline ...
'else' newline ...
'    use_solar = false;' newline ...
'end' newline ...
'' newline ...
'%% Decision 2: Bid formulation (humidity-based priority)' newline ...
'if btn_n1 >= 0.5' newline ...
'    bid_n1 = BID_H;' newline ...
'elseif rh_n1 >= RH_CRIT' newline ...
'    bid_n1 = BID_H;' newline ...
'else' newline ...
'    bid_n1 = BID_L;' newline ...
'end' newline ...
'' newline ...
'if btn_n2 >= 0.5' newline ...
'    bid_n2 = BID_H;' newline ...
'elseif rh_n2 >= RH_CRIT' newline ...
'    bid_n2 = BID_H;' newline ...
'else' newline ...
'    bid_n2 = BID_L;' newline ...
'end' newline ...
'' newline ...
'%% Market clearing' newline ...
'if use_solar' newline ...
'    source_mode = 1;' newline ...
'    if bid_n1 >= bid_n2' newline ...
'        winner = 1;' newline ...
'    else' newline ...
'        winner = 2;' newline ...
'    end' newline ...
'    relay_K1 = 1;' newline ...
'    relay_n1 = 1;' newline ...
'    relay_n2 = 1;' newline ...
'else' newline ...
'    source_mode = 0;' newline ...
'    winner      = 0;' newline ...
'    relay_K1    = 0;' newline ...
'    relay_n1    = 1;' newline ...
'    relay_n2    = 1;' newline ...
'end' newline ...
'' newline ...
'%% JFI' newline ...
'if E1_cum == 0 && E2_cum == 0' newline ...
'    jfi = 1.0;' newline ...
'elseif (E1_cum^2 + E2_cum^2) < 1e-9' newline ...
'    jfi = 1.0;' newline ...
'else' newline ...
'    jfi = (E1_cum + E2_cum)^2 / (2.0*(E1_cum^2 + E2_cum^2));' newline ...
'end' newline ...
'jfi = min(max(jfi,0.0),1.0);' newline ...
'end' newline ...
];

    try
        rt = sfroot();
        charts = rt.find('-isa','Stateflow.EMChart');
        % Find the one belonging to ss2_auction_ctrl
        for k = 1:numel(charts)
            if contains(charts(k).Path, 'ss2_auction_ctrl')
                charts(k).Script = code;
                fprintf('[OK]  Auction code updated (grid quality added as input 8)\n');
                return;
            end
        end
        % Fallback: update last chart
        if ~isempty(charts)
            charts(end).Script = code;
            fprintf('[OK]  Auction code updated\n');
        end
    catch ME
        % Write to file for manual paste
        fid = fopen('auction_engine_updated.m','w');
        fprintf(fid,'%s',code);
        fclose(fid);
        fprintf('[INFO] Code written to auction_engine_updated.m\n');
        fprintf('       Paste into Auction_Engine block manually.\n');
    end
end